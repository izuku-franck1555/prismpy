def test_label_suffixes_name_their_numbers(tmp_path):
    decl = sd.declared_soil(_craft(tmp_path, HWSD2, ["ML00001469", "ML00001470"], ptf_layers=3,
                                   organic_layers=1, andic_layers=2, cells_with_flagged_layers=2,
                                   chem_defaulted="bulk_density:2,organic_carbon:0,ph:1"), "craft")
    assert decl.label == (
        sd.SOURCE_DESCRIPTIONS["hwsd"] + ", one profile per grid cell; water limits estimated with a pedotransfer "
        "function (Saxton & Rawls 2006, simplified) for 3 of 5 layers; 1 of 2 profiles are shallower than 100 cm "
        "(depth 60–60 cm); chemistry defaults used (bulk density 1.40 g/cm³ ×2, pH 6.5 ×1); 1 organic and 2 "
        "andic layers (of 5 layers in 1 profiles; 2 cells), outside the pedotransfer function's calibration range")
    assert decl.record["hydraulics"] == {**sd.HYDRAULICS, "estimated_layers": 3, "layers": 5}


def _profile(pid, **hydraulics):
    return SoilProfile(profile_id=pid, lat=12.0, lon=-5.0, source="isda",
                       layers=[SoilLayer(depth_top=0.0, depth_bottom=0.2, sand=50.0, clay=20.0, **hydraulics)])


def test_the_pedotransfer_mark_is_provenance_only_and_survives_dedup():
    layer = SoilLayer(depth_top=0.0, depth_bottom=0.2, sand=50.0, clay=20.0)
    plain = SoilLayer(depth_top=0.0, depth_bottom=0.2, sand=50.0, clay=20.0)
    assert not layer.hydraulics_estimated
    layer.estimate_hydraulic_properties()
    assert layer.hydraulics_estimated and "hydraulics_estimated" not in layer.to_dict()
    plain.estimate_hydraulic_properties()
    plain.hydraulics_estimated = False
    assert plain == layer                         # the mark is outside equality
    supplied = {k: getattr(layer, k) for k in ("wilting_point", "field_capacity", "saturated_wc")}
    grid = SpatialGrid(resolution="5arcmin", cells=[GridCell(cell_id=i, lat=12.0, lon=-5.0 + i / 12, row=0, col=i)
                                                     for i in (1, 2)])
    # the lower cell id supplies the same water limits the function gives; the higher one lacks them
    _, profiles = assign_cell_to_profile_id(grid, {1: _profile("a", **supplied), 2: _profile("b")})
    assert len(profiles) == 1 and profiles[1].layers[0].hydraulics_estimated
    assert profiles[1].profile_id == "a"
